#!/usr/bin/env python3
"""Generate the reviewed, nonsecret environment bundle embedded in Nexus."""
import base64
import json
from pathlib import Path
import zlib

root = Path(__file__).resolve().parent.parent
source = root / 'integrations/ansible'
files = {name: base64.b64encode((source / name).read_bytes()).decode() for name in ('environment.py', 'requirements.lock')}
payload = base64.b64encode(zlib.compress(json.dumps(files, sort_keys=True, separators=(',', ':')).encode(), 9)).decode()
target = root / 'nexus/internal/ansibleenv/bundle_generated.go'
target.write_text('// Code generated by scripts/generate_ansible_bundle.py; DO NOT EDIT.\npackage ansibleenv\n\nconst bundle = ' + json.dumps(payload) + '\n')
print('Generated reviewed Ansible environment bundle:', len(payload), 'bytes')
